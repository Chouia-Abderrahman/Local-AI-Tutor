"""Builds Local AI Tutor's Android icons and splash resources.

Run from the project root: python3 tool/branding/make_icons.py

The mark is an open book (two pages) with a spark above the spine, on a
24-unit grid: the same geometry as AppMark in lib/app/ui.dart. Vector
drawables cover Android 8+ (adaptive and themed icons, the splash screen and
the notification icon); PNGs cover Android 7 and the store listing.
Needs Pillow.
"""
import os

from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

INK = "#15171C"
PAPER = "#F1EFEA"
AMBER = "#F0AE4C"

LEFT_PAGE = [(2, 9.2), (11, 11.4), (11, 21), (2, 18.8)]
RIGHT_PAGE = [(13, 11.4), (22, 9.2), (22, 18.8), (13, 21)]
SPARK_CENTER, SPARK_RADIUS = (12.0, 4.6), 3.6

LEFT_PATH = "M2,9.2 L11,11.4 L11,21 L2,18.8 Z"
RIGHT_PATH = "M13,11.4 L22,9.2 L22,18.8 L13,21 Z"
SPARK_PATH = "M12,1 Q12,4.6 15.6,4.6 Q12,4.6 12,8.2 Q12,4.6 8.4,4.6 Q12,4.6 12,1 Z"


def spark_points(steps=24):
    cx, cy = SPARK_CENTER
    r = SPARK_RADIUS
    corners = [(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)]
    points = []
    for i in range(4):
        p0, p2 = corners[i], corners[(i + 1) % 4]
        for s in range(steps):
            t = s / steps
            x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * cx + t ** 2 * p2[0]
            y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * cy + t ** 2 * p2[1]
            points.append((x, y))
    return points


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def vector(size_dp, viewport, scale, tx, ty, pages, spark, extra=""):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/make_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{extra}    <group
        android:scaleX="{scale}"
        android:scaleY="{scale}"
        android:translateX="{tx}"
        android:translateY="{ty}">
        <path android:fillColor="{pages}" android:pathData="{LEFT_PATH}" />
        <path android:fillColor="{pages}" android:pathData="{RIGHT_PATH}" />
        <path android:fillColor="{spark}" android:pathData="{SPARK_PATH}" />
    </group>
</vector>
"""


def vectors():
    # Adaptive icon layers: 108 dp, the mark centered in the 66 dp safe zone.
    scale = 2.25
    tx, ty = 54 - 12 * scale, 54 - 11 * scale
    write(
        os.path.join(RES, "drawable", "ic_launcher_foreground.xml"),
        vector(108, 108, scale, tx, ty, PAPER, AMBER),
    )
    write(
        os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
        vector(108, 108, scale, tx, ty, "#FFFFFFFF", "#FFFFFFFF"),
    )
    # Notification icon: white on transparent; Android tints it.
    write(
        os.path.join(RES, "drawable", "ic_stat_tutor.xml"),
        vector(24, 24, 1, 0, 0, "#FFFFFFFF", "#FFFFFFFF"),
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/make_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), adaptive)
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher_round.xml"), adaptive)
    write(
        os.path.join(RES, "values", "colors.xml"),
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/make_icons.py. -->
<resources>
    <color name="ic_launcher_background">{INK}</color>
    <color name="brand_ink">{INK}</color>
    <color name="brand_amber">{AMBER}</color>
</resources>
""",
    )


def splash():
    # Before Android 12: the window background while the app starts.
    layer = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/make_icons.py. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/brand_ink" />
    <item
        android:width="108dp"
        android:height="108dp"
        android:drawable="@drawable/ic_launcher_foreground"
        android:gravity="center" />
</layer-list>
"""
    write(os.path.join(RES, "drawable", "launch_background.xml"), layer)
    write(os.path.join(RES, "drawable-v21", "launch_background.xml"), layer)
    # Android 12 and later draw their own splash from these attributes.
    styles = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/make_icons.py. -->
<resources>
    <style name="LaunchTheme" parent="@android:style/Theme.Black.NoTitleBar">
        <item name="android:windowBackground">@drawable/launch_background</item>
        <item name="android:windowSplashScreenBackground">@color/brand_ink</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/ic_launcher_foreground</item>
    </style>
    <style name="NormalTheme" parent="@android:style/Theme.Black.NoTitleBar">
        <item name="android:windowBackground">?android:colorBackground</item>
    </style>
</resources>
"""
    write(os.path.join(RES, "values-v31", "styles.xml"), styles)
    write(os.path.join(RES, "values-night-v31", "styles.xml"), styles)


def raster(size, shape):
    """The icon as a PNG: 'square' (low radius), 'circle' or 'full'."""
    ss = 8
    big = size * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    if shape == "full":
        draw.rectangle([0, 0, big, big], fill=INK)
        mark_width = 0.6
    elif shape == "circle":
        m = big * 0.02
        draw.ellipse([m, m, big - m, big - m], fill=INK)
        mark_width = 0.56
    else:
        m = big * 0.04
        draw.rounded_rectangle([m, m, big - m, big - m], radius=big * 0.1, fill=INK)
        mark_width = 0.62
    s = big * mark_width / 20

    def tr(points):
        return [(big / 2 + (x - 12) * s, big / 2 + (y - 11) * s) for x, y in points]

    draw.polygon(tr(LEFT_PAGE), fill=PAPER)
    draw.polygon(tr(RIGHT_PAGE), fill=PAPER)
    draw.polygon(tr(spark_points()), fill=AMBER)
    return img.resize((size, size), Image.LANCZOS)


def pngs():
    for density, size in [
        ("mdpi", 48),
        ("hdpi", 72),
        ("xhdpi", 96),
        ("xxhdpi", 144),
        ("xxxhdpi", 192),
    ]:
        folder = os.path.join(RES, f"mipmap-{density}")
        os.makedirs(folder, exist_ok=True)
        raster(size, "square").save(os.path.join(folder, "ic_launcher.png"))
        raster(size, "circle").save(os.path.join(folder, "ic_launcher_round.png"))
    store = os.path.join(ROOT, "android", "app", "src", "main", "ic_launcher-playstore.png")
    raster(512, "full").save(store)


if __name__ == "__main__":
    vectors()
    splash()
    pngs()
    print("icons written to", os.path.normpath(RES))
